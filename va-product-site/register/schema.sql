CREATE TABLE IF NOT EXISTS va_donors (
  email VARCHAR(254) NOT NULL PRIMARY KEY,
  full_name VARCHAR(255) NOT NULL DEFAULT '',
  donated_at VARCHAR(40) NOT NULL DEFAULT '',
  added_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_serial_requests (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(254) NOT NULL,
  serial VARCHAR(100) NOT NULL,
  lang VARCHAR(8) NOT NULL DEFAULT 'en',
  ip VARCHAR(45) NOT NULL DEFAULT '',
  user_agent VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL,
  mailed_at DATETIME NULL,
  UNIQUE KEY uq_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_register_attempts (
  ip VARCHAR(45) NOT NULL,
  created_at DATETIME NOT NULL,
  KEY ix_ip_created (ip, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_purchases (
  order_id VARCHAR(40) NOT NULL PRIMARY KEY,
  email VARCHAR(254) NOT NULL,
  lang VARCHAR(8) NOT NULL DEFAULT 'en',
  amount VARCHAR(16) NOT NULL DEFAULT '',
  currency VARCHAR(3) NOT NULL DEFAULT '',
  state VARCHAR(16) NOT NULL DEFAULT 'created',
  capture_id VARCHAR(40) NOT NULL DEFAULT '',
  payer_email VARCHAR(254) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL,
  fulfilled_at DATETIME NULL,
  KEY ix_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_download_counts (
  day DATE NOT NULL,
  file_key VARCHAR(40) NOT NULL,
  count INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (day, file_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_activations (
  email VARCHAR(254) NOT NULL PRIMARY KEY,
  version VARCHAR(20) NOT NULL DEFAULT '',
  os VARCHAR(20) NOT NULL DEFAULT '',
  activations INT UNSIGNED NOT NULL DEFAULT 1,
  first_at DATETIME NOT NULL,
  last_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_bug_reports (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  status VARCHAR(12) NOT NULL DEFAULT 'new',
  summary VARCHAR(200) NOT NULL,
  description TEXT NOT NULL,
  email VARCHAR(254) NOT NULL DEFAULT '',
  version VARCHAR(20) NOT NULL DEFAULT '',
  os VARCHAR(40) NOT NULL DEFAULT '',
  lang VARCHAR(8) NOT NULL DEFAULT '',
  licensed TINYINT(1) NOT NULL DEFAULT 0,
  sysinfo TEXT NULL,
  errors MEDIUMTEXT NULL,
  note TEXT NULL,
  ip VARCHAR(45) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL,
  updated_at DATETIME NULL,
  KEY ix_status (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_bug_attachments (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  report_id INT UNSIGNED NOT NULL,
  name VARCHAR(200) NOT NULL DEFAULT '',
  mime VARCHAR(40) NOT NULL,
  width INT UNSIGNED NOT NULL DEFAULT 0,
  height INT UNSIGNED NOT NULL DEFAULT 0,
  size INT UNSIGNED NOT NULL DEFAULT 0,
  data MEDIUMBLOB NOT NULL,
  KEY ix_report (report_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_installs (
  id CHAR(32) NOT NULL PRIMARY KEY,
  version VARCHAR(20) NOT NULL DEFAULT '',
  os VARCHAR(20) NOT NULL DEFAULT '',
  lang VARCHAR(8) NOT NULL DEFAULT '',
  launches INT UNSIGNED NOT NULL DEFAULT 0,
  days INT UNSIGNED NOT NULL DEFAULT 0,
  minutes INT UNSIGNED NOT NULL DEFAULT 0,
  supporter TINYINT(1) NOT NULL DEFAULT 0,
  country CHAR(2) NOT NULL DEFAULT '',
  first_at DATETIME NOT NULL,
  last_at DATETIME NOT NULL,
  KEY ix_last (last_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_install_days (
  day DATE NOT NULL,
  id CHAR(32) NOT NULL,
  version VARCHAR(20) NOT NULL DEFAULT '',
  os VARCHAR(20) NOT NULL DEFAULT '',
  launches INT UNSIGNED NOT NULL DEFAULT 0,
  minutes INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (day, id),
  KEY ix_id (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_messages (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  active TINYINT(1) NOT NULL DEFAULT 1,
  rev INT UNSIGNED NOT NULL DEFAULT 0,
  audience VARCHAR(12) NOT NULL DEFAULT '',
  level VARCHAR(8) NOT NULL DEFAULT 'info',
  caption_en VARCHAR(200) NOT NULL DEFAULT '',
  caption_hu VARCHAR(200) NOT NULL DEFAULT '',
  title_en VARCHAR(200) NOT NULL DEFAULT '',
  body_en TEXT NOT NULL,
  title_hu VARCHAR(200) NOT NULL DEFAULT '',
  body_hu TEXT NOT NULL,
  url VARCHAR(500) NOT NULL DEFAULT '',
  image MEDIUMBLOB NULL,
  image_mime VARCHAR(40) NOT NULL DEFAULT '',
  min_version VARCHAR(20) NOT NULL DEFAULT '',
  max_version VARCHAR(20) NOT NULL DEFAULT '',
  os VARCHAR(20) NOT NULL DEFAULT '',
  starts_at DATETIME NULL,
  ends_at DATETIME NULL,
  created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_message_views (
  message_id INT UNSIGNED NOT NULL,
  install_id CHAR(32) NOT NULL,
  seen_at DATETIME NOT NULL,
  PRIMARY KEY (message_id, install_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_geoip (
  ip_from BINARY(16) NOT NULL PRIMARY KEY,
  ip_to BINARY(16) NOT NULL,
  country CHAR(2) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=ascii;
CREATE TABLE IF NOT EXISTS va_settings (
  k VARCHAR(40) NOT NULL PRIMARY KEY,
  v VARCHAR(255) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS va_support_threads (
