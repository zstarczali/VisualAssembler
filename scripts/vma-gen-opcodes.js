#!/usr/bin/env node
// Writes <VMA_DIR>/src/opcodes.rs (the VMA repository, default ../VMA) from the app's opcodeMap, so the Rust VMA compiler
// uses the same mnemonic × addressing mode table. Run after a change to opcodeMap.
const fs = require("node:fs");
const path = require("node:path");
const loadApp = require("../tests/helpers/load-app");

const MODES = ["implied", "immediate", "zeroPage", "zeroPageX", "zeroPageY", "absolute", "absoluteX",
  "absoluteY", "indirect", "indirectX", "indirectY", "relative"];
const RUST = ["Implied", "Immediate", "ZeroPage", "ZeroPageX", "ZeroPageY", "Absolute", "AbsoluteX",
  "AbsoluteY", "Indirect", "IndirectX", "IndirectY", "Relative"];

const map = loadApp().run("opcodeMap");
const rows = [];
for (const [mnem, modes] of Object.entries(map)) {
  for (const [mode, code] of Object.entries(modes)) {
    const i = MODES.indexOf(mode);
    if (i < 0) throw new Error(`unknown mode ${mode} of ${mnem}`);
    rows.push(`    ("${mnem}", Mode::${RUST[i]}, 0x${code.toString(16).toUpperCase().padStart(2, "0")}),`);
  }
}
const out = `// Generated by scripts/vma-gen-opcodes.js from the opcodeMap of www/app.js. Do not edit.

use crate::parse::Mode;

pub static OPCODES: &[(&str, Mode, u8)] = &[
${rows.join("\n")}
];
`;
fs.writeFileSync(path.join(require("../tests/helpers/vma-cli").vmaDir(), "src", "opcodes.rs"), out);
console.log(`${rows.length} opcodes`);
